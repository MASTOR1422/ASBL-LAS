-- Compatibilité avec le premier schéma LAS si ses tables ont déjà été créées.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='members' and column_name='display_name')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='members' and column_name='name') then
    alter table public.members rename column display_name to name;
  end if;
end $$;

