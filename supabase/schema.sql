create or replace function public.current_las_role()
returns text language sql stable security definer set search_path = public, auth
as $$
  select role from public.profiles where id = auth.uid() and active = true limit 1
$$;

create or replace function public.is_las_active()
returns boolean language sql stable security definer set search_path = public, auth
as $$
  select exists(select 1 from public.profiles where id = auth.uid() and active = true)
$$;

create or replace function public.sync_las_member_identity()
returns void language plpgsql security definer set search_path = public, auth
as $$
begin
  if coalesce(public.current_las_role(),'') <> 'admin' then
    raise exception 'Administrator role required';
  end if;
  perform setval(
    pg_get_serial_sequence('public.members','id'),
    coalesce((select max(id) from public.members), 0) + 1,
    false
  );
end;
$$;
revoke all on function public.sync_las_member_identity() from public;
grant execute on function public.sync_las_member_identity() to authenticated;

