-- ASBL LAS — base de données initiale et politiques Row Level Security (RLS)
-- À exécuter dans Supabase SQL Editor après création du projet.
-- IMPORTANT : créer les comptes dans Supabase Auth, puis renseigner profiles avec leur UUID.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  member_id bigint unique,
  display_name text not null,
  role text not null default 'membre' check (role in ('admin','tresorier','secretaire','membre')),
  active boolean not null default false,
  birthday_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  display_name text not null,
  phone text,
  email text,
  birthdate date,
  birthplace text,
  address text,
  profession text,
  position text,
  joined_on date,
  status text not null default 'active' check (status in ('active','inactive','suspended')),
  forum_status text,
  meeting_status text,
  note text,
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 180),
  body text not null check (char_length(body) between 1 and 10000),
  category text not null default 'general' check (category in ('general','annonce','entraide','evenement')),
  status text not null default 'published' check (status in ('published','hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists members_birthdate_idx on public.members (birthdate);
create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists posts_author_id_idx on public.posts (author_id);

alter table public.profiles enable row level security;
alter table public.members enable row level security;
alter table public.posts enable row level security;

create or replace function public.current_las_role()
returns text language sql stable security definer set search_path = public
as $$
  select role from public.profiles
  where id = auth.uid() and active = true
  limit 1
$$;

create or replace function public.is_las_staff()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and active = true
      and role in ('admin','secretaire','tresorier')
  )
$$;

drop policy if exists "profiles_read_authenticated" on public.profiles;
create policy "profiles_read_authenticated" on public.profiles
for select to authenticated using (id = auth.uid() or public.current_las_role() = 'admin');

drop policy if exists "members_read_authenticated" on public.members;
create policy "members_read_authenticated" on public.members
for select to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.active = true)
);

drop policy if exists "members_insert_staff" on public.members;
create policy "members_insert_staff" on public.members
for insert to authenticated with check (public.current_las_role() in ('admin','secretaire'));

drop policy if exists "members_update_staff" on public.members;
create policy "members_update_staff" on public.members
for update to authenticated using (public.current_las_role() in ('admin','secretaire'))
with check (public.current_las_role() in ('admin','secretaire'));

drop policy if exists "members_delete_admin" on public.members;
create policy "members_delete_admin" on public.members
for delete to authenticated using (public.current_las_role() = 'admin');

drop policy if exists "posts_read_published" on public.posts;
create policy "posts_read_published" on public.posts
for select to authenticated using (
  status = 'published'
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.active = true)
  or public.current_las_role() = 'admin'
);

drop policy if exists "posts_create_active_member" on public.posts;
create policy "posts_create_active_member" on public.posts
for insert to authenticated with check (
  author_id = auth.uid()
  and exists (select 1 from public.profiles p where p.id = auth.uid() and p.active = true)
);

drop policy if exists "posts_update_author_or_admin" on public.posts;
create policy "posts_update_author_or_admin" on public.posts
for update to authenticated using (
  author_id = auth.uid() or public.current_las_role() = 'admin'
) with check (
  author_id = auth.uid() or public.current_las_role() = 'admin'
);

drop policy if exists "posts_delete_author_or_admin" on public.posts;
create policy "posts_delete_author_or_admin" on public.posts
for delete to authenticated using (
  author_id = auth.uid() or public.current_las_role() = 'admin'
);

grant usage on schema public to authenticated;
grant select on public.profiles, public.members, public.posts to authenticated;
grant insert, update on public.members to authenticated;
grant delete on public.members to authenticated;
grant insert, update, delete on public.posts to authenticated;

