-- ASBL-LAS V2 — proposition de migration NON appliquée automatiquement.
-- Précondition: comparer avec le schéma et les migrations déjà appliquées sur Supabase.
-- Cette migration est additive; elle ne supprime ni table ni donnée existante.
begin;

-- Un membre peut lire sa propre fiche; les rôles de gestion conservent leurs politiques existantes.
drop policy if exists members_read_self on public.members;
create policy members_read_self on public.members
for select to authenticated
using (
  id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

-- Un membre peut lire seulement ses cotisations. Les politiques de gestion existantes
-- restent applicables et sont combinées par OR par PostgreSQL.
drop policy if exists contributions_read_self on public.monthly_contributions;
create policy contributions_read_self on public.monthly_contributions
for select to authenticated
using (
  member_id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

drop policy if exists member_payments_read_self on public.member_payments;
create policy member_payments_read_self on public.member_payments
for select to authenticated
using (
  member_id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

-- Journaliser les modifications des deux registres de cotisations/paiements.
drop trigger if exists monthly_contributions_audit on public.monthly_contributions;
create trigger monthly_contributions_audit
after insert or update or delete on public.monthly_contributions
for each row execute function public.audit_row_change();

drop trigger if exists member_payments_audit on public.member_payments;
create trigger member_payments_audit
after insert or update or delete on public.member_payments
for each row execute function public.audit_row_change();

-- Module de tontine: les périodes sont administrées par les responsables habilités.
create table if not exists public.tontine_periods (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  starts_on date not null,
  ends_on date not null,
  contribution_amount numeric(12,2) not null check (contribution_amount >= 0),
  currency char(3) not null default 'CDF' check (currency in ('CDF','USD')),
  status text not null default 'planned' check (status in ('planned','open','closed','cancelled')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on >= starts_on)
);

create table if not exists public.tontine_entries (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.tontine_periods(id) on delete restrict,
  member_id bigint not null references public.members(id) on delete restrict,
  amount numeric(12,2) not null check (amount >= 0),
  currency char(3) not null default 'CDF' check (currency in ('CDF','USD')),
  status text not null default 'due' check (status in ('due','paid','late','waived')),
  paid_at timestamptz,
  note text,
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(period_id, member_id)
);

alter table public.tontine_periods enable row level security;
alter table public.tontine_entries enable row level security;
grant select, insert, update, delete on table public.tontine_periods to authenticated;
grant select, insert, update, delete on table public.tontine_entries to authenticated;

drop policy if exists tontine_periods_read_active on public.tontine_periods;
create policy tontine_periods_read_active on public.tontine_periods
for select to authenticated
using ((select private.is_las_active()));

drop policy if exists tontine_periods_manage_finance on public.tontine_periods;
create policy tontine_periods_manage_finance on public.tontine_periods
for all to authenticated
using ((select private.has_role('admin')) or (select private.has_role('tresorier')))
with check ((select private.has_role('admin')) or (select private.has_role('tresorier')));

drop policy if exists tontine_entries_read_self on public.tontine_entries;
create policy tontine_entries_read_self on public.tontine_entries
for select to authenticated
using (
  member_id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

drop policy if exists tontine_entries_read_finance on public.tontine_entries;
create policy tontine_entries_read_finance on public.tontine_entries
for select to authenticated
using ((select private.has_role('admin')) or (select private.has_role('tresorier')));

drop policy if exists tontine_entries_manage_finance on public.tontine_entries;
create policy tontine_entries_manage_finance on public.tontine_entries
for all to authenticated
using ((select private.has_role('admin')) or (select private.has_role('tresorier')))
with check ((select private.has_role('admin')) or (select private.has_role('tresorier')));

-- Demandes d'entraide: confidentialité par défaut, accès à la demande pour son auteur
-- et accès de traitement pour l'équipe habilitée.
create table if not exists public.aid_requests (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete restrict,
  subject text not null check (char_length(subject) between 3 and 160),
  description text not null check (char_length(description) between 3 and 5000),
  status text not null default 'submitted' check (status in ('submitted','under_review','approved','declined','closed')),
  decision_note text,
  decided_by uuid references auth.users(id) on delete set null,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.aid_requests enable row level security;
grant select, insert, update, delete on table public.aid_requests to authenticated;

drop policy if exists aid_requests_read_self on public.aid_requests;
create policy aid_requests_read_self on public.aid_requests
for select to authenticated
using (
  member_id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

drop policy if exists aid_requests_insert_self on public.aid_requests;
create policy aid_requests_insert_self on public.aid_requests
for insert to authenticated
with check (
  member_id = (
    select p.member_id from public.profiles p
    where p.id = (select auth.uid()) and p.active = true
    limit 1
  )
);

drop policy if exists aid_requests_manage_staff on public.aid_requests;
create policy aid_requests_manage_staff on public.aid_requests
for all to authenticated
using (
  (select private.has_role('admin')) or
  (select private.has_role('secretaire')) or
  (select private.has_role('tresorier'))
)
with check (
  (select private.has_role('admin')) or
  (select private.has_role('secretaire')) or
  (select private.has_role('tresorier'))
);

-- Exposer uniquement les colonnes nécessaires aux contenus publiés; aucun storage_path n'est public.
revoke select on table public.media_items from anon;
grant select (id, media_type, title, description, external_url, published_date, status) on table public.media_items to anon;
drop policy if exists media_public_read_anon on public.media_items;
create policy media_public_read_anon on public.media_items
for select to anon
using (status = 'published' and external_url is not null and external_url ~* '^https://');

-- Seules les annonces et activités publiées sont accessibles sans connexion.
revoke select on table public.posts from anon;
grant select (id, title, body, category, created_at, status) on table public.posts to anon;
drop policy if exists posts_public_read_anon on public.posts;
create policy posts_public_read_anon on public.posts
for select to anon
using (status = 'published' and category in ('annonce', 'evenement'));

-- Les modifications financières et demandes d'aide laissent une trace consultable
-- uniquement par les administrateurs via la politique audit_read_admin existante.
drop trigger if exists tontine_periods_audit on public.tontine_periods;
create trigger tontine_periods_audit after insert or update or delete
on public.tontine_periods for each row execute function public.audit_row_change();

drop trigger if exists tontine_entries_audit on public.tontine_entries;
create trigger tontine_entries_audit after insert or update or delete
on public.tontine_entries for each row execute function public.audit_row_change();

drop trigger if exists aid_requests_audit on public.aid_requests;
create trigger aid_requests_audit after insert or update or delete
on public.aid_requests for each row execute function public.audit_row_change();

create index if not exists tontine_entries_member_period_idx
on public.tontine_entries(member_id, period_id);
create index if not exists aid_requests_member_status_idx
on public.aid_requests(member_id, status, created_at desc);

commit;
