with check ((select public.has_role('admin')) or (select public.has_role('secretariat')));

drop policy if exists media_update_secretariat_admin on public.media_items;
create policy media_update_secretariat_admin on public.media_items
for update to authenticated
using ((select public.has_role('admin')) or (select public.has_role('secretariat')))
