begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'reader'
    check (role in ('admin', 'secretariat', 'treasurer', 'reader')),
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text,
  profession text,
  birthdate date,
  birthplace text,
  address text,
  joined date,
  poste text,
  forum text check (forum is null or forum in
    ('OUI', 'NON', 'PARTIEL', 'OCCASIONEL', 'SOUVENT', 'PARFOIS')),
  asbl text not null default 'OUI' check (asbl in ('OUI', 'NON')),
  reunion text check (reunion is null or reunion in ('OUI', 'NON', 'EXEMPTER', 'EXEMPTE')),
  note text,
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.monthly_contributions (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete restrict,
  contribution_year smallint not null check (contribution_year between 2000 and 2200),
  contribution_month smallint not null check (contribution_month between 1 and 12),
  amount numeric(10,2) not null check (amount >= 0),
  currency char(3) not null default 'USD' check (currency in ('USD', 'CDF')),
  paid_at timestamptz not null default now(),
  note text,
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (member_id, contribution_year, contribution_month)
);

create table if not exists public.media_items (
  id bigint generated by default as identity primary key,
  media_type text not null check (media_type in ('photo', 'pdf', 'video', 'article')),
  title text not null,
  description text,
  external_url text,
  storage_path text,
  published_date date not null default current_date,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (external_url is not null or storage_path is not null or media_type = 'article')
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  old_data jsonb,
  new_data jsonb,
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

create index if not exists members_name_idx on public.members (name);
create index if not exists members_phone_idx on public.members (phone);
create index if not exists contributions_member_year_idx
  on public.monthly_contributions (member_id, contribution_year);
create index if not exists audit_logs_changed_at_idx on public.audit_logs (changed_at desc);

create or replace function public.has_role(required_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.role = required_role
  );
$$;

revoke all on function public.has_role(text) from public;
grant execute on function public.has_role(text) to authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists members_set_updated_at on public.members;
create trigger members_set_updated_at
before update on public.members
for each row execute function public.set_updated_at();

create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_row jsonb;
  new_row jsonb;
  row_id text;
begin
  if tg_op = 'INSERT' then
    new_row := to_jsonb(new);
    row_id := new_row ->> 'id';
  elsif tg_op = 'UPDATE' then
    old_row := to_jsonb(old);
    new_row := to_jsonb(new);
    row_id := coalesce(new_row ->> 'id', old_row ->> 'id');
  else
    old_row := to_jsonb(old);
    row_id := old_row ->> 'id';
  end if;

  insert into public.audit_logs (table_name, record_id, action, old_data, new_data, changed_by)
  values (tg_table_name, row_id, tg_op, old_row, new_row, (select auth.uid()));

  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists members_audit on public.members;
create trigger members_audit after insert or update or delete on public.members
for each row execute function public.audit_row_change();

drop trigger if exists contributions_audit on public.monthly_contributions;
create trigger contributions_audit after insert or update or delete on public.monthly_contributions
for each row execute function public.audit_row_change();

drop trigger if exists media_items_audit on public.media_items;
create trigger media_items_audit after insert or update or delete on public.media_items
for each row execute function public.audit_row_change();

alter table public.profiles enable row level security;
alter table public.members enable row level security;
alter table public.monthly_contributions enable row level security;
alter table public.media_items enable row level security;
alter table public.audit_logs enable row level security;

revoke all on table public.profiles, public.members, public.monthly_contributions,
  public.media_items, public.audit_logs from anon, authenticated;

grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.members to authenticated;
grant select, insert, update, delete on public.monthly_contributions to authenticated;
grant select, insert, update, delete on public.media_items to authenticated;
grant select on public.audit_logs to authenticated;

-- Les utilisateurs ne peuvent lire que leur profil; les administrateurs peuvent lire tous les profils.
drop policy if exists profiles_read_self_or_admin on public.profiles;
create policy profiles_read_self_or_admin on public.profiles
for select to authenticated
using (id = (select auth.uid()) or (select public.has_role('admin')));

-- Les fiches sont visibles par tous les comptes authentifiés.
drop policy if exists members_read_authenticated on public.members;
create policy members_read_authenticated on public.members
for select to authenticated using (true);

drop policy if exists members_insert_secretariat_admin on public.members;
create policy members_insert_secretariat_admin on public.members
for insert to authenticated
with check ((select public.has_role('admin')) or (select public.has_role('secretariat')));

drop policy if exists members_update_secretariat_admin on public.members;
create policy members_update_secretariat_admin on public.members
for update to authenticated
using ((select public.has_role('admin')) or (select public.has_role('secretariat')))
with check ((select public.has_role('admin')) or (select public.has_role('secretariat')));

drop policy if exists members_delete_admin on public.members;
create policy members_delete_admin on public.members
for delete to authenticated
using ((select public.has_role('admin')));

-- Les paiements sont consultables par les utilisateurs authentifiés;
-- seul le trésorier ou l'administrateur peut les enregistrer/corriger.
drop policy if exists contributions_read_authenticated on public.monthly_contributions;
create policy contributions_read_authenticated on public.monthly_contributions
for select to authenticated using (true);

drop policy if exists contributions_insert_finance on public.monthly_contributions;
create policy contributions_insert_finance on public.monthly_contributions
for insert to authenticated
with check ((select public.has_role('admin')) or (select public.has_role('treasurer')));

drop policy if exists contributions_update_finance on public.monthly_contributions;
create policy contributions_update_finance on public.monthly_contributions
for update to authenticated
using ((select public.has_role('admin')) or (select public.has_role('treasurer')))
with check ((select public.has_role('admin')) or (select public.has_role('treasurer')));

drop policy if exists contributions_delete_admin on public.monthly_contributions;
create policy contributions_delete_admin on public.monthly_contributions
for delete to authenticated
using ((select public.has_role('admin')));

-- Les médias sont consultables par les comptes authentifiés.
drop policy if exists media_read_authenticated on public.media_items;
create policy media_read_authenticated on public.media_items
for select to authenticated using (true);

drop policy if exists media_insert_secretariat_admin on public.media_items;
create policy media_insert_secretariat_admin on public.media_items
